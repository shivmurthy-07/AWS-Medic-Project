async function main() {
    console.log('--- POPULATING COMPREHENSIVE ADDRESS DETAILS FOR ALL DOCTORS ---');
    const doctors = await prisma.doctor.findMany();

    for (const doc of doctors) {
        const addrProfile = DOCTOR_ADDRESS_PROFILES[doc.email];
        if (addrProfile) {
            await prisma.doctor.update({
                where: { id: doc.id },
                data: addrProfile,
            });
            console.log(`Updated address for Dr. ${doc.firstName} ${doc.lastName} (${doc.email}):`);
            console.log(`  Res: ${addrProfile.address}, ${addrProfile.city}, ${addrProfile.state} - ${addrProfile.postalCode}`);
            console.log(`  Clinic: ${addrProfile.clinicName} (${addrProfile.clinicAddress})`);
            console.log(`  Hospital: ${addrProfile.hospitalName} (${addrProfile.hospitalAddress})`);
        } else {
            const fallback = {
                address: '42, 10th Cross, 4th Main, Indiranagar',
                city: 'Bangalore',
                state: 'Karnataka',
                postalCode: '560038',
                country: 'India',
                clinicName: 'MediConnect Prime Health Clinic',
                clinicAddress: '100 Feet Road, Indiranagar, Near Metro Pillar 12',
                hospitalName: 'Manipal Hospital',
                hospitalAddress: '98, HAL Old Airport Road, Bangalore, Karnataka 560017',
            };
            await prisma.doctor.update({
                where: { id: doc.id },
                data: fallback,
            });
            console.log(`Fallback address applied to Dr. ${doc.firstName} ${doc.lastName}`);
        }
    }
    console.log(`Successfully populated complete addresses for all ${doctors.length} doctors!`);
}

main().catch(console.error).finally(() => prisma.$disconnect());

